"""
api/security_headers.py — one source of truth for baseline response headers.

The headers must be present on every response class, including responses that
do not travel through the normal route handler (404, 405, 413, 429) and the
500 generated by Starlette's outermost ``ServerErrorMiddleware``. The error
handlers therefore apply the same helper as the HTTP middleware.
"""
from __future__ import annotations

from starlette.requests import Request
from starlette.responses import Response

import config

BASE_SECURITY_HEADERS: tuple[tuple[str, str], ...] = (
    ("X-Content-Type-Options", "nosniff"),
    ("X-Frame-Options", "DENY"),
    ("Referrer-Policy", "no-referrer"),
    ("Cross-Origin-Opener-Policy", "same-origin"),
    ("X-Permitted-Cross-Domain-Policies", "none"),
)

PERMISSIONS_POLICY = (
    "geolocation=(), microphone=(), camera=(), payment=()"
)

HSTS_VALUE = "max-age=63072000; includeSubDomains; preload"


def is_https_request(request: Request) -> bool:
    """True when the effective client scheme is HTTPS (direct or proxied)."""
    forwarded_proto = (request.headers.get("x-forwarded-proto") or "").lower()
    forwarded_hdr = (request.headers.get("forwarded") or "").lower()
    return (
        request.url.scheme == "https"
        or forwarded_proto == "https"
        or "proto=https" in forwarded_hdr
    )


def content_security_policy(request: Request) -> str:
    directives = [
        "default-src 'self'",
        "script-src 'self'",
        "style-src 'self' 'unsafe-inline'",
        "img-src 'self' data: https:",
        "font-src 'self' data:",
        "connect-src 'self' ws: wss:",
        "object-src 'none'",
        # A base tag can rewrite every relative URL on the page. The app never
        # needs one, so forbid it outright instead of allowing 'self'.
        "base-uri 'none'",
        "frame-ancestors 'none'",
        "form-action 'self'",
    ]
    if is_https_request(request) or getattr(config, "FORCE_HTTPS", True):
        directives.append("upgrade-insecure-requests")
    return "; ".join(directives)


def apply_security_headers(request: Request, response: Response) -> Response:
    """Attach the baseline headers without overwriting a route-specific value."""
    for name, value in BASE_SECURITY_HEADERS:
        response.headers.setdefault(name, value)

    response.headers.setdefault(
        "Content-Security-Policy", content_security_policy(request)
    )
    # X-XSS-Protection intentionally NOT set: deprecated and disabled in all
    # modern browsers (it was an IE-era header that auditing flags as stale).
    response.headers.setdefault("Permissions-Policy", PERMISSIONS_POLICY)

    if is_https_request(request):
        response.headers.setdefault("Strict-Transport-Security", HSTS_VALUE)
    if request.url.path.startswith("/api/"):
        response.headers.setdefault("Cache-Control", "no-store")
    return response
